"""Emit the outlines of the ruler's digits for the GPUI editor (#213).

The desk's left ruler stands its numbers on their side (React's
`rotate(-90)` on an svg `<text>`), and gpui 0.2.2 paints a glyph without a
transform. The digits are drawn as filled paths instead, from the editor's
own figures face at the ruler's weight (`jetbrains-mono-500.ttf`, the
`--fm` family at `font-weight: 500`, `Rulers.tsx` / `desk.module.css`).

Every contour is flattened with fontTools' own quadratic decomposition (a
`BasePen`), so the outlines are the font's shapes, not an approximation of
them: each quadratic segment becomes STEPS line segments.

Usage:
    python tools/gpui-outlines/gen_ruler_glyphs.py
"""
import os

from fontTools.pens.basePen import BasePen
from fontTools.ttLib import TTFont

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, '..', '..'))
FONT = os.path.join(ROOT, 'app', 'gpui', 'assets', 'fonts', 'jetbrains-mono-500.ttf')
OUT = os.path.join(ROOT, 'app', 'gpui', 'src', 'views', 'layout', 'ruler_glyphs.rs')

CHARS = '0123456789.'
STEPS = 8


class Flatten(BasePen):
    def __init__(self, glyph_set):
        super().__init__(glyph_set)
        self.contours = []
        self.current = []

    def _moveTo(self, pt):
        self.current = [pt]

    def _lineTo(self, pt):
        self.current.append(pt)

    def _qCurveToOne(self, pt1, pt2):
        p0 = self.current[-1]
        for i in range(1, STEPS + 1):
            t = i / STEPS
            u = 1 - t
            self.current.append((
                u * u * p0[0] + 2 * u * t * pt1[0] + t * t * pt2[0],
                u * u * p0[1] + 2 * u * t * pt1[1] + t * t * pt2[1],
            ))

    def _curveToOne(self, pt1, pt2, pt3):
        p0 = self.current[-1]
        for i in range(1, STEPS + 1):
            t = i / STEPS
            u = 1 - t
            self.current.append((
                u ** 3 * p0[0] + 3 * u * u * t * pt1[0] + 3 * u * t * t * pt2[0] + t ** 3 * pt3[0],
                u ** 3 * p0[1] + 3 * u * u * t * pt1[1] + 3 * u * t * t * pt2[1] + t ** 3 * pt3[1],
            ))

    def _closePath(self):
        pts = self.current
        if len(pts) > 1 and pts[0] == pts[-1]:
            pts = pts[:-1]
        if len(pts) >= 3:
            self.contours.append(pts)
        self.current = []

    _endPath = _closePath


def main():
    font = TTFont(FONT)
    upm = font['head'].unitsPerEm
    glyphs = font.getGlyphSet()
    cmap = font.getBestCmap()
    advance = font['hmtx'][cmap[ord('0')]][0]
    lines = [
        '//! The outlines of the desk ruler\'s digits (#213). Generated by',
        '//! `tools/gpui-outlines/gen_ruler_glyphs.py` from `jetbrains-mono-500.ttf`;',
        '//! do not edit by hand.',
        '//!',
        '//! The left ruler\'s numbers stand on their side in React (`rotate(-90)`);',
        '//! gpui 0.2.2 cannot turn a glyph, so `stage.rs` fills these contours turned.',
        '',
        f'/// The face\'s units per em.',
        f'pub const UNITS_PER_EM: f32 = {float(upm):.1f};',
        f'/// The advance of one character (the face is monospaced).',
        f'pub const ADVANCE: f32 = {float(advance):.1f};',
        '',
        '/// One closed polygon, in font units (y up).',
        "pub type Contour = &'static [(f32, f32)];",
        "/// One character's contours.",
        "pub type Glyph = &'static [Contour];",
        '',
        '/// The digits and the point, by character.',
        'pub const GLYPHS: &[(char, Glyph)] = &[',
    ]
    for ch in CHARS:
        pen = Flatten(glyphs)
        glyphs[cmap[ord(ch)]].draw(pen)
        lines.append(f"    ('{ch}', &[")
        for c in pen.contours:
            pts = ', '.join(f'({x:.1f}, {y:.1f})' for x, y in c)
            lines.append(f'        &[{pts}],')
        lines.append('    ]),')
    lines.append('];')
    lines.append('')
    with open(OUT, 'w', encoding='utf8', newline='\n') as f:
        f.write('\n'.join(lines))
    print('wrote', OUT)


if __name__ == '__main__':
    main()
